/** Smart translator that handles exact matches, trimmed colons, emojis, counters and navigation turns */
export function translateText(key: string, lang: LanguageId): string {
  if (!key || lang === "en") return key;
  const dict = dictionaries[lang];
  if (!dict) return key;

  // 1. Exact match
  if (dict[key]) return dict[key];

  const trimmed = key.trim();
  if (dict[trimmed]) return dict[trimmed];

  // 2. Trailing punctuation match (e.g. "Predicted Risk:" -> translation of "Predicted Risk" + ":")
  if (trimmed.endsWith(":")) {
    const base = trimmed.slice(0, -1).trim();
    if (dict[base]) return dict[base] + ":";
  }

  // 3. Emoji prefix match (e.g. "🛰️ 3D Satellite View Active" or "⚠️ Danger Point")
  const emojiMatch = key.match(/^([\p{Emoji}\u200d\uFE0F\s]+)(.+)$/u);
  if (emojiMatch) {
    const prefix = emojiMatch[1];
    const rest = emojiMatch[2].trim();
    if (dict[rest]) return `${prefix}${dict[rest]}`;
  }

  // 4. Directional maneuver instructions
  let translated = key;
  const directionalPhrases = [
    ["Turn right onto", dict["Turn right onto"] || dict["Turn right"] || "Turn right"],
    ["Turn left onto", dict["Turn left onto"] || dict["Turn left"] || "Turn left"],
    ["Turn right", dict["Turn right"] || "Turn right"],
    ["Turn left", dict["Turn left"] || "Turn left"],
    ["Continue straight onto", dict["Continue straight onto"] || dict["Continue straight"] || "Continue straight"],
    ["Continue onto", dict["Continue onto"] || dict["Continue straight"] || "Continue straight"],
    ["Continue straight", dict["Continue straight"] || "Continue straight"],
    ["Make a U-turn", dict["Make a U-turn"] || "Make a U-turn"],
    ["Arrive at destination", dict["Arrive at destination"] || "Arrive at destination"],
    ["via", dict["via"] || "via"],
  ];
  for (const [src, dst] of directionalPhrases) {
    if (dst && translated.includes(src)) {
      translated = translated.replace(src, dst);
      return translated;
    }
  }

  // 5. Dynamic status counters (e.g. "5 active", "24 navigation instructions", "12 shown")
  const counterMatch = key.match(/^(\d+)\s+(.+)$/);
  if (counterMatch) {
    const num = counterMatch[1];
    const phrase = counterMatch[2].trim();
    const transPhrase = dict[phrase] || dict[phrase.toLowerCase()];
    if (transPhrase) {
      return `${num} ${transPhrase}`;
    }
  }

  // 6. Case-insensitive match fallback
  const lowerKey = trimmed.toLowerCase();
  for (const [k, v] of Object.entries(dict)) {
    if (k.toLowerCase() === lowerKey) return v;
  }

  return dict[key] ?? key;
}

type Ctx = { lang: LanguageId; setLang: (l: LanguageId) => void; t: (key: string) => string };
const LanguageContext = createContext<Ctx | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLang] = useState<LanguageId>(() => {
    if (typeof window !== "undefined") {
      const stored = window.localStorage.getItem("ner-language") as LanguageId | null;
      if (stored && languages.some((l) => l.id === stored)) return stored;
    }
    return "en";
  });

  useEffect(() => {
    if (typeof window !== "undefined") {
      const stored = window.localStorage.getItem("ner-language") as LanguageId | null;
      if (stored && languages.some((l) => l.id === stored)) {
        setLang(stored);
        document.documentElement.lang = stored;
      }
    }
  }, []);

  const change = useCallback((next: LanguageId) => {
    setLang(next);
    if (typeof window !== "undefined") {
      try {
        window.localStorage.setItem("ner-language", next);
        document.documentElement.lang = next;
      } catch {}
    }
  }, []);

  const t = useCallback(
    (key: string) => translateText(key, lang),
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang: change, t }), [lang, change, t]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useI18n must be used inside LanguageProvider");
  return ctx;
}
